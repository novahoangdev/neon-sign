// Perf-only Metro config: loaded through EXPO_OVERRIDE_METRO_CONFIG by tools/perf/start.sh, never by the normal
// `expo start`. It redirects `./App` imported from app/index.ts to app/src/perf/PerfApp.tsx (App + FPS overlay),
// so the overlay can be measured without touching any shared source file.
// PERF_OFF=steam,grade,wall,glow,blur,decor swaps a layer for a trivial stand-in (app/src/perf/variants) to measure
// what each layer costs — A/B only, the real files are untouched.
const path = require("path");
const appDir = path.resolve(__dirname, "../../app");
const { getDefaultConfig } = require(require.resolve("expo/metro-config", { paths: [appDir] }));

const appRoot = appDir;
const config = getDefaultConfig(appRoot);
const perfApp = path.join(appRoot, "src/perf/PerfApp.tsx");
const entry = path.join(appRoot, "index.ts");
const V = (f) => path.join(appRoot, "src/perf/variants", f);
const OFF = new Set((process.env.PERF_OFF || "").split(",").filter(Boolean));
// PERF_FAST=wall,post,tube: optimised shader variants generated by tools/perf/mkvariants.py (proposed diffs)
const FAST = new Set((process.env.PERF_FAST || "").split(",").filter(Boolean));
const inApp = (p) => p.startsWith(path.join(appRoot, "src")) && !p.includes("/src/perf/");
const from = (ctx, rel) => ctx.originModulePath === path.join(appRoot, "src", rel);

const upstream = config.resolver.resolveRequest;
config.resolver.resolveRequest = (context, moduleName, platform) => {
  const file = (f) => ({ type: "sourceFile", filePath: f });
  if (moduleName === "./App" && context.originModulePath === entry && process.env.PERF_ENTRY !== "0") return file(perfApp);
  // POLISH_SCENE=1: App.tsx gets the POLISH preview of NeonScene (tools/perf/mkscene.py)
  if (process.env.POLISH_SCENE === "1" && moduleName === "./src/scene/NeonScene" && context.originModulePath === path.join(appRoot, "App.tsx"))
    return file(V("NeonScenePolish.tsx"));
  // PERF_AUDIO_STUB=1: installed native build predates expo-audio → no-op stub instead of a red-box
  if (moduleName === "expo-audio" && process.env.PERF_AUDIO_STUB === "1") return file(path.join(appRoot, "src/perf/audioStub.ts"));
  if (from(context, "scene/NeonScene.tsx")) {
    if (OFF.has("wall") && moduleName === "../shaders/wall") return file(V("wallOff.ts"));
    if (FAST.has("wall") && moduleName === "../shaders/wall") return file(V("wallFast.ts"));
    if (FAST.has("post") && moduleName === "../shaders/post") return file(V("postFast.ts"));
    if (FAST.has("tube") && moduleName === "../neon/Tube") return file(V("TubeFast.tsx"));
    if ((OFF.has("steam") || OFF.has("grade")) && moduleName === "../shaders/post") return file(V("postOff.ts"));
    if (OFF.has("decor") && moduleName === "../neon/Decor") return file(V("decorOff.tsx"));
  }
  if (moduleName === "react-native-skia" && inApp(context.originModulePath)) {
    if (OFF.has("blur") || (OFF.has("glow") && from(context, "neon/Tube.tsx"))) return file(V("skiaNoBlur.ts"));
  }
  return upstream ? upstream(context, moduleName, platform) : context.resolveRequest(context, moduleName, platform);
};
// separate transform cache per variant
config.cacheVersion = `${config.cacheVersion ?? ""}-perf-${process.env.POLISH_SCENE ?? ""}${process.env.PERF_ENTRY ?? ""}-${[...OFF].sort().join("+")}-${[...FAST].sort().join("+")}`;
module.exports = config;
