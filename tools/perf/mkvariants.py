#!/usr/bin/env python3
"""Generate the optimised shader variants from the CURRENT app sources (so A/B always tracks the latest code):
   app/src/shaders/wall.ts → app/src/perf/variants/wallFast.ts, post.ts → postFast.ts.
   Each replacement below is one proposed change (see notes/perf.md); a replacement that no longer matches fails loudly."""
import pathlib, sys
APP = pathlib.Path(__file__).resolve().parents[2] / "app/src"
OUT = APP / "perf/variants"

def patch(src, reps, name):
    s = src
    for tag, a, b in reps:
        if a not in s:
            sys.exit(f"[{name}] '{tag}' no longer matches the source — update tools/perf/mkvariants.py")
        s = s.replace(a, b)
    return s

wall = (APP / "shaders/wall.ts").read_text()
WALL = [
    # W1: skip atlas tiles whose 3 slots are all dark (uniform branch; demo uses 2-3 of 4 tiles, 0 when off)
    ("W1 tile skip",
     "  for (int t = 0; t < 4; t++) {\n    float3 s =",
     "  for (int t = 0; t < 4; t++) {\n    if (bright[t * 3] + bright[t * 3 + 1] + bright[t * 3 + 2] <= 0.0) continue;\n    float3 s ="),
    # W2: puddle reflection of the lit wall: blurry + rippled, so plain albedo × light (1 atlas read, no N·L
    #     gradient = 2 fewer atlas reads, no normal/data fetch) instead of the full surf()
    ("W2 cheap reflected wall",
     "    float rq;\n    float3 wallN = surf(q, rq);",
     "    float3 wallN = lightAt(q) * toLin(albedo.eval(q * imgK).rgb) * gain * 0.8;"),
    # W3: vertical blur of reflected tubes: 2 taps at ±s/2 instead of 3
    ("W3 2-tap tube blur",
     "    float3 tb = tubesAt(q) * 0.5\n              + tubesAt(q + float2(0.0, s)) * 0.25\n              + tubesAt(q - float2(0.0, s)) * 0.25;",
     "    float3 tb = (tubesAt(q + float2(0.0, s * 0.5)) + tubesAt(q - float2(0.0, s * 0.5))) * 0.5;"),
]
post = (APP / "shaders/post.ts").read_text()
POST = [
    ("import", 'from "./wall"', 'from "./wallFast"'),
    # P1: steam fbm only where the steam band is non-zero (top ~half of the screen skips 15 noise evaluations)
    ("P1 band early-out",
     "  float2 sp = p * float2(0.010, 0.016);",
     "  float band = smoothstep(horizon - 330.0, horizon - 10.0, p.y) * (1.0 - 0.55 * smoothstep(horizon + 20.0, view.y, p.y));\n"
     "  if (band * density < 0.002) {\n    float3 c0 = pow(max(L * haze, float3(0.0)), float3(1.0 / 2.2)) * 0.9;\n    return half4(half3(c0), 1.0);\n  }\n"
     "  float2 sp = p * float2(0.010, 0.016);"),
    ("P1 band dup",
     "  float band = smoothstep(horizon - 330.0, horizon - 10.0, p.y) * (1.0 - 0.55 * smoothstep(horizon + 20.0, view.y, p.y));\n  float d =",
     "  float d ="),
    # P2: 3-octave fbm for the two domain-warp lookups (low-frequency anyway), 5 octaves kept for the density
    ("P2 fbm3 warp",
     "float fbm(float2 p) {",
     "float fbm3(float2 p) {\n  float s = 0.0, a = 0.5;\n  for (int i = 0; i < 3; i++) { s += a * n2(p); p = p * 2.03 + float2(17.1, 3.7); a *= 0.5; }\n  return s + 0.0625;\n}\nfloat fbm(float2 p) {"),
    ("P2 use fbm3",
     "float2 w = float2(fbm(sp + float2(0.0, time * 0.05)), fbm(sp + float2(5.2, 1.3) - float2(time * 0.03, 0.0)));",
     "float2 w = float2(fbm3(sp + float2(0.0, time * 0.05)), fbm3(sp + float2(5.2, 1.3) - float2(time * 0.03, 0.0)));"),
]
hdr = "// GENERATED by tools/perf/mkvariants.py from app/src/shaders/{} — perf A/B only, do not edit.\n"
(OUT / "wallFast.ts").write_text(hdr.format("wall.ts") + patch(wall, WALL, "wall"))
(OUT / "postFast.ts").write_text(hdr.format("post.ts") + patch(post, POST, "post"))
print("ok", OUT / "wallFast.ts", OUT / "postFast.ts")
